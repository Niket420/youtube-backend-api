import mongoose, {isValidObjectId} from "mongoose"
import {Video} from "../models/videos.model.js"
import {APIError} from "../utils/APIError.js"
import {APIResponse} from "../utils/APIResponse.js"
import {asyncHandler} from "../utils/asynchandler.js"
import {uploadOnCloudinary} from "../utils/cloudinary.js"



const getAllVideos = asyncHandler(async (req, res) => {

    const { page = 1, limit = 10, query, sortBy, sortType, userId } = req.query

    const getVideos = async ({
        page,
        limit,
        query,
        sortBy,
        sortType,
        userId
    }) => {

        page = parseInt(page)
        limit = parseInt(limit)

        const skip = (page - 1) * limit

        let filter = {}

        if (query) {
            filter.title = { $regex: query, $options: "i" }
        }

        if (userId && isValidObjectId(userId)) {
            filter.owner = userId
        }

        let sortOptions = {}

        if (sortBy) {
            sortOptions[sortBy] = sortType === "asc" ? 1 : -1
        } else {
            sortOptions.createdAt = -1
        }

        const videos = await Video.find(filter)
            .sort(sortOptions)
            .skip(skip)
            .limit(limit)

        const total = await Video.countDocuments(filter)

        return {
            total,
            totalPages: Math.ceil(total / limit),
            page,
            videos
        }
    }

    const result = await getVideos({
        page,
        limit,
        query,
        sortBy,
        sortType,
        userId
    })

    return res.status(200).json(
        new APIResponse(200, result, "Videos fetched successfully")
    )
})

const publishAVideo = asyncHandler(async (req, res) => {

    const { title, description } = req.body

    const videoFile = req.files?.video?.[0]
    const thumbnailFile = req.files?.thumbnail?.[0]

    if (!title || !description) {
        throw new APIError(400, "Please fill all details")
    }

    if (!videoFile) {
        throw new APIError(400, "Video not selected")
    }

    const uploadVideo = await uploadOnCloudinary(videoFile.path)

    if (!uploadVideo?.secure_url) {
        throw new APIError(500, "Video upload failed")
    }

    let thumbnail

    if (thumbnailFile) {

        const uploadedThumbnail = await uploadOnCloudinary(thumbnailFile.path)

        thumbnail = {
            url: uploadedThumbnail.secure_url,
            public_id: uploadedThumbnail.public_id
        }

    } else {

        const autogenerated = cloudinary.url(uploadVideo.public_id, {
            resource_type: "video",
            format: "jpg",
            transformation: [{ start_offset: "2" }]
        })

        thumbnail = {
            url: autogenerated,
            public_id: uploadVideo.public_id
        }
    }

    const video = await Video.create({
        videofile: uploadVideo.secure_url,
        thumbnail,
        title,
        description,
        duration: uploadVideo.duration,
        views: 0,
        isPublished: true,
        owner: req.user._id
    })

    return res.status(201).json(
        new APIResponse(201, video, "Successfully uploaded")
    )
})

const getVideoById = asyncHandler(async (req, res) => {
    const { videoId } = req.params

    const searchedVideo = await Video.findById(videoId)
    if(!searchedVideo){
        throw new APIError(404,"Video Not Found")
    }

    return res.status(200)
                .json(new APIResponse(200,searchedVideo,"Video Found"))
    
})

const updateVideo = asyncHandler(async (req, res) => {

    const { videoId } = req.params
    const { newtitle, newdescription } = req.body
    const thumbnailFile = req.file

    if (!isValidObjectId(videoId)) {
        throw new APIError(400, "Invalid Video ID")
    }

    const oldVideo = await Video.findById(videoId)

    if (!oldVideo) {
        throw new APIError(404, "Video not found")
    }

    let thumbnailUrl = oldVideo.thumbnail

    if (thumbnailFile) {

        if (oldVideo.thumbnail?.public_id) {
            await cloudinary.uploader.destroy(oldVideo.thumbnail.public_id)
        }

        const uploadedThumbnail = await uploadOnCloudinary(thumbnailFile.path)

        thumbnailUrl = {
            url: uploadedThumbnail.secure_url,
            public_id: uploadedThumbnail.public_id
        }
    }

    const updatedVideo = await Video.findByIdAndUpdate(
        videoId,
        {
            $set: {
                title: newtitle || oldVideo.title,
                description: newdescription || oldVideo.description,
                thumbnail: thumbnailUrl
            }
        },
        { new: true }
    )

    return res.status(200).json(
        new APIResponse(200, updatedVideo, "Video updated successfully")
    )
})


const deleteVideo = asyncHandler(async (req, res) => {

    const { videoId } = req.params

    if (!isValidObjectId(videoId)) {
        throw new APIError(400, "Invalid video ID")
    }

    const video = await Video.findById(videoId)

    if (!video) {
        throw new APIError(404, "Video not found")
    }

    if (video.owner.toString() !== req.user._id.toString()) {
        throw new APIError(403, "Not authorized to delete this video")
    }

    if (video.thumbnail?.public_id) {
        await cloudinary.uploader.destroy(video.thumbnail.public_id)
    }

    await Video.findByIdAndDelete(videoId)

    return res.status(200).json(
        new APIResponse(200, {}, "Video deleted successfully")
    )
})




const togglePublishStatus = asyncHandler(async (req, res) => {

    const { videoId } = req.params

    const video = await Video.findById(videoId)

    if (!video) {
        throw new APIError(404, "Video not found")
    }

    if (!video.owner.equals(req.user._id)) {
        throw new APIError(403, "Authorization denied")
    }

    video.isPublished = !video.isPublished

    await video.save()

    return res.status(200)
              .json(new APIResponse(200, video, "Video successfully toggled"))
})

export {
    getAllVideos,
    publishAVideo,
    getVideoById,
    updateVideo,
    deleteVideo,
    togglePublishStatus
}
